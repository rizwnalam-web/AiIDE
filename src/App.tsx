function TerminalLine({ content, searchQuery }: { content: string, searchQuery?: string }) {
  const isCommand = content.startsWith("➜");
  const isError = content.startsWith("Error:") || content.startsWith("Failed:") || content.startsWith("⚠");
  const isSuccess = content.startsWith("✓");

  // Highlight matches
  const highlightSearch = (text: string) => {
    if (!searchQuery || !text.toLowerCase().includes(searchQuery.toLowerCase())) {
      return text;
    }

    const parts = text.split(new RegExp(`(${searchQuery.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&')})`, 'gi'));
    return (
      <>
        {parts.map((part, i) => 
          part.toLowerCase() === searchQuery.toLowerCase() ? (
            <mark key={i} className="bg-vscode-blue/40 text-white rounded-[2px] px-0.5">{part}</mark>
          ) : part
        )}
      </>
    );
  };

  // Simple shell syntax highlighting
  const renderLine = (text: string) => {
    if (isCommand) {
      const parts = text.split(" ");
      return (
        <span>
          <span className="text-agent-teal">➜ </span>
          <span className="text-vscode-blue font-bold tracking-tight">
            {highlightSearch(parts[1] || "")}
          </span>
          <span className="text-[#cccccc] opacity-80 pl-1">
            {highlightSearch(parts.slice(2).join(" "))}
          </span>
        </span>
      );
    }
    
    return (
      <span className={cn(
        "leading-relaxed",
        isError ? "text-red-400" : isSuccess ? "text-green-400" : "text-[#cccccc]"
      )}>
        {highlightSearch(text)}
      </span>
    );
  };

  return (
    <div className="mb-0.5 leading-relaxed whitespace-pre-wrap break-all hover:bg-white/[0.02] px-1 rounded transition-colors group/line flex gap-2">
       <span className="text-[9px] text-white/10 select-none font-mono mt-1 group-hover/line:text-white/30 w-5 text-right flex-shrink-0">
          {(Math.floor(Math.random() * 90) + 10).toString()}
       </span>
       <div className="flex-1 min-w-0">
          {renderLine(content)}
       </div>
    </div>
  );
}

